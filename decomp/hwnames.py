"""Writes hw.h, the names of the Saturn's registers and memory areas, and puts them in the decompiled C.

    python decomp/hwnames.py            # rewrite hw.h from saturnrecomp.hw
    python decomp/hwnames.py --apply    # replace the addresses in src/*.c that hw.h names
    python decomp/hwnames.py --check    # fail if hw.h is out of date or src/ holds an address it names

Addresses are the cache-through ones the game uses (0x25xxxxxx, 0x2010xxxx), so a name expands to the literal
it replaces and the generated code does not change.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "saturn-recomp", "src"))
from saturnrecomp import hw  # noqa: E402

HEADER = os.path.join(HERE, "hw.h")
THROUGH = 0x20000000

# Areas a register table does not cover. VDP2's four 128 KiB banks are the ones the game maps at reset.
AREAS = {
    "SCSP_RAM": 0x05A00000, "SCSP_REGS": 0x05B00000, "VDP1_VRAM": 0x05C00000, "VDP1_FB": 0x05C80000,
    "VDP2_VRAM": 0x05E00000, "VDP2_VRAM_A1": 0x05E20000, "VDP2_VRAM_B0": 0x05E40000, "VDP2_VRAM_B1": 0x05E60000,
    "VDP2_CRAM": 0x05F00000,
}


def names() -> dict[str, int]:
    """Macro name -> address, for every register hw.py names and the areas above."""
    found = {}
    for prefix, table, base in (("VDP1", hw.VDP1, 0x05D00000), ("VDP2", hw.VDP2, 0x05F80000),
                                ("SCU", hw.SCU, 0x05FE0000), ("SMPC", hw.SMPC, 0x00100000),
                                ("CD", hw.CDBLOCK, 0x05800000)):
        for offset, register in table.items():
            if register != "-":
                found["%s_%s" % (prefix, register)] = base + offset
    found.update(AREAS)
    found = {name: THROUGH | address for name, address in found.items()}
    found.update({"SH2_" + register: 0xFFFF0000 | offset for offset, register in hw.ONCHIP.items()})
    found["CD_DATA"] = THROUGH | 0x05898000
    del found["CD_DATATRNS"]
    return found


def header() -> str:
    lines = ["/* Generated by hwnames.py from saturnrecomp.hw; edit that, not this. */",
             "#ifndef HW_H", "#define HW_H", ""]
    for name, address in sorted(names().items(), key=lambda item: (item[1], item[0])):
        lines.append("#define %-14s 0x%08X" % (name, address))
    lines += ["", "#define SMPC_IREG(n) (SMPC_IREG0 + 2 * (n))", "#define SMPC_OREG(n) (SMPC_OREG0 + 2 * (n))", "",
              "#endif", ""]
    return "\n".join(lines)


def literals(text: str) -> list[tuple[int, int, int]]:
    return [(m.start(), m.end(), int(m.group(), 16)) for m in re.finditer(r"\b0[xX][0-9A-Fa-f]{8}\b", text)]


def apply_to(text: str, by_address: dict[int, str]) -> str:
    out, last = [], 0
    for start, end, value in literals(text):
        if value in by_address:
            out += [text[last:start], by_address[value]]
            last = end
    return "".join(out) + text[last:]


def by_address() -> dict[int, str]:
    """The address -> name table. The registers from 0xFFFFFF00 up are left out: those words are as often a
    mask such as -16 as an address."""
    return {address: name for name, address in sorted(names().items(), key=lambda item: (-len(item[0]), item[0]))
            if address < 0xFFFFFF00}


def sources() -> list[str]:
    where = os.path.join(HERE, "src")
    return [os.path.join(where, f) for f in sorted(os.listdir(where)) if f.endswith(".c")]


def main() -> int:
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    if mode == "":
        open(HEADER, "w").write(header())
        return 0
    table = by_address()
    stale = 0
    for path in sources() + [os.path.join(HERE, "krnl.h")]:
        text = open(path).read()
        new = apply_to(text, table)
        if new != text and mode == "--apply":
            open(path, "w").write(new)
        elif new != text:
            print("%s holds an address hw.h names" % os.path.basename(path))
            stale = 1
    if mode == "--check" and open(HEADER).read() != header():
        print("hw.h is out of date")
        stale = 1
    return stale


if __name__ == "__main__":
    sys.exit(main())
