def _parse(source: str) -> dict[str, tuple[str, ...]]:
    glyphs = {}
    for block in source.strip().split("\n\n"):
        char, *rows = block.split("\n")
        assert len(rows) == HEIGHT and all(len(row) == WIDTH for row in rows), char
        glyphs[char] = tuple(rows)
    return glyphs


GLYPHS = _parse(_SOURCE)


def cells(text: str) -> list[tuple[int, int]]:
    """The lit cells of the text as (column, row) pairs, left to right from (0, 0). A character with no glyph is blank."""
    lit = []
    for index, char in enumerate(text.upper()):
        for row, line in enumerate(GLYPHS.get(char, ())):
            lit.extend((index * ADVANCE + column, row) for column, mark in enumerate(line) if mark == "#")
    return lit


def width(text: str) -> int:
    """The width in cells, without the gap after the last character."""
    return max(len(text) * ADVANCE - 1, 0)
